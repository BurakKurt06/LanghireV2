"""Secrets at rest: Windows DPAPI (this Windows user only), plus per-employer passwords.

`protect(text)` -> "dpapi:v1:<base64>" on Windows (CryptProtectData, user scope);
`reveal(value)` turns it back, and passes plain (legacy, unmigrated) values through
so existing settings keep working until they are rewritten encrypted.

On other systems (unsupported here, kept for development) values stay plain and
the files are made owner-only.

Employer passwords (`site_password`): each employer site gets its own random
password, generated by the app the first time an account is needed and stored
encrypted here. One leaked or phished site password then can't unlock the
user's other employer accounts (Settings keeps only the legacy shared password
for signing in to accounts created before).
"""
from __future__ import annotations

import base64
import json
import os
import secrets as _random
import string
import sys
import threading
from pathlib import Path

PREFIX = "dpapi:v1:"
_lock = threading.Lock()


class SecretError(RuntimeError):
    """A protected value couldn't be decrypted (another Windows user, a damaged file)."""


def _dpapi(data: bytes, protect: bool) -> bytes:
    import ctypes
    from ctypes import wintypes

    class Blob(ctypes.Structure):
        _fields_ = [("cbData", wintypes.DWORD), ("pbData", ctypes.POINTER(ctypes.c_char))]

    crypt32, kernel32 = ctypes.windll.crypt32, ctypes.windll.kernel32
    buffer = ctypes.create_string_buffer(data, len(data))
    source = Blob(len(data), ctypes.cast(buffer, ctypes.POINTER(ctypes.c_char)))
    out = Blob()
    flags = 0x1  # CRYPTPROTECT_UI_FORBIDDEN
    fn = crypt32.CryptProtectData if protect else crypt32.CryptUnprotectData
    ok = (fn(ctypes.byref(source), None, None, None, None, flags, ctypes.byref(out)) if protect else
          fn(ctypes.byref(source), None, None, None, None, flags, ctypes.byref(out)))
    if not ok:
        raise SecretError(f"DPAPI {'protect' if protect else 'unprotect'} failed ({ctypes.GetLastError()})")
    try:
        return ctypes.string_at(out.pbData, out.cbData)
    finally:
        kernel32.LocalFree(out.pbData)


def available() -> bool:
    return sys.platform == "win32"


def is_protected(value) -> bool:
    return isinstance(value, str) and value.startswith(PREFIX)


def protect(text: str) -> str:
    """Encrypt for this Windows user. Empty and already-protected values are returned as they are."""
    if not text or not isinstance(text, str) or is_protected(text) or not available():
        return text
    sealed = PREFIX + base64.b64encode(_dpapi(text.encode("utf-8"), True)).decode("ascii")
    if reveal(sealed) != text:  # never store something that can't be read back
        raise SecretError("encrypted value didn't read back")
    return sealed


def reveal(value: str) -> str:
    """The plain value (plain legacy values pass through)."""
    if not is_protected(value):
        return value
    if not available():
        raise SecretError("encrypted value on a system without DPAPI")
    return _dpapi(base64.b64decode(value[len(PREFIX):]), False).decode("utf-8")


def protect_paths(data: dict, paths: list[tuple[str, ...]]) -> dict:
    """A copy of `data` with the values at `paths` (key tuples) encrypted."""
    return _map_paths(data, paths, protect)


def reveal_paths(data: dict, paths: list[tuple[str, ...]]) -> dict:
    """A copy of `data` with the values at `paths` decrypted (unreadable ones become "")."""
    def safe_reveal(value):
        try:
            return reveal(value)
        except Exception:
            return ""
    return _map_paths(data, paths, safe_reveal)


def _map_paths(data: dict, paths, fn) -> dict:
    out = json.loads(json.dumps(data or {}))
    for path in paths:
        node = out
        for key in path[:-1]:
            node = node.get(key) if isinstance(node, dict) else None
            if node is None:
                break
        if isinstance(node, dict) and isinstance(node.get(path[-1]), str):
            node[path[-1]] = fn(node[path[-1]])
    return out


def restrict_file(path: Path) -> None:
    """Owner-only permissions where the OS honours chmod (no effect on Windows ACLs)."""
    try:
        os.chmod(path, 0o600)
    except OSError:
        pass


# ── Per-employer passwords ───────────────────────────────────────────────────
def _vault_path() -> Path:
    try:
        from core.config import get_data_dir
    except ImportError:  # pragma: no cover
        from backend.core.config import get_data_dir
    return get_data_dir() / "site_credentials.json"


def _load_vault() -> dict:
    try:
        return json.loads(_vault_path().read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}


def generate_password(length: int = 20) -> str:
    """A random password that meets the usual complexity rules (upper, lower, digit, symbol)."""
    pools = [string.ascii_uppercase, string.ascii_lowercase, string.digits, "!@#$%^*-_=+"]
    chars = [_random.choice(pool) for pool in pools]
    chars += [_random.choice("".join(pools)) for _ in range(length - len(chars))]
    _random.SystemRandom().shuffle(chars)
    return "".join(chars)


def site_password(site: str, create: bool = True, *, migrate_from: str | None = None) -> str:
    """The app-generated password for one employer site ("" if none and create=False).

    Saved (encrypted) before it is returned, so a password typed into a sign-up
    form is never lost.
    """
    site = (site or "").strip().lower()
    if not site:
        return ""
    with _lock:
        vault = _load_vault()
        entry = vault.get(site)
        if entry:
            try:
                return reveal(entry["password"])
            except Exception:
                return ""
        if not create:
            return ""
        # Only trusted approval code supplies migrate_from. The old entry is
        # retained; this never silently aliases a newly approved origin.
        previous = vault.get(migrate_from or "")
        password = reveal(previous["password"]) if previous else generate_password()
        vault[site] = {"password": protect(password)}
        path = _vault_path()
        tmp = path.with_suffix(".tmp")
        tmp.write_text(json.dumps(vault, indent=1), encoding="utf-8")
        tmp.replace(path)
        restrict_file(path)
        return password


def site_password_sites() -> list[str]:
    """The employer sites that have an app-generated password (for display, never the passwords)."""
    return sorted(_load_vault())
